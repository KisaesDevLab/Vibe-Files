//! Synthetic fixture cabinet (PHASES P00 step 8). No real client data, ever.
//!
//! - 5 clients, tax years 2024 and 2025, 60 PDFs, laid out in Filer Desktop's default template
//!   (`{Client} ({ID})/Income Tax/{Year}/…`) with real SentinelV1 files.
//! - SSNs only from 987-65-4320..=987-65-4329, the range the SSA reserves for advertising and
//!   never issues. EINs only with prefixes the IRS never assigned (07, 08, 09, 17, 18, 19, 28, 29).
//!   Both still match the usual SSN/EIN patterns, so PII detection (P04/P06) must flag them.
//! - Deterministic: the same seed gives the same names, numbers, files, and PDF bytes. Sentinel
//!   and cabinet ids are derived from the seed; only `created_at` times differ between runs.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use filer_core::clients::Client;
use pdf_writer::{Content, Name, Pdf, Rect, Ref, Str};
use uuid::Uuid;
use vf_fs::cabinet::{self, CabinetFile};

pub const MARKER: &str = ".vf-fixture";
pub const YEARS: [u16; 2] = [2024, 2025];

/// SSA advertising range: never issued.
pub fn synthetic_ssn(n: u64) -> String {
    format!("987-65-432{}", n % 10)
}

/// IRS prefixes never assigned to any campus.
const NEVER_ISSUED_EIN_PREFIXES: [u8; 8] = [7, 8, 9, 17, 18, 19, 28, 29];

pub fn synthetic_ein(rng: &mut Rng) -> String {
    let p = NEVER_ISSUED_EIN_PREFIXES[(rng.next_u64() % 8) as usize];
    format!("{p:02}-{:07}", rng.next_u64() % 10_000_000)
}

/// xorshift64*: deterministic, no extra dependency.
pub struct Rng(u64);

impl Rng {
    pub fn new(seed: u64) -> Self {
        Self(seed.max(1))
    }
    pub fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn pick<'a>(&mut self, xs: &'a [&'a str]) -> &'a str {
        xs[(self.next_u64() % xs.len() as u64) as usize]
    }
    fn uuid(&mut self) -> Uuid {
        let b = ((self.next_u64() as u128) << 64) | self.next_u64() as u128;
        uuid::Builder::from_random_bytes(b.to_le_bytes()).into_uuid()
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Individual,
    Business,
}

pub struct FixtureClient {
    pub id: &'static str,
    pub name: String,
    pub kind: Kind,
}

/// One generated document.
#[derive(Debug, Clone)]
pub struct FixtureDoc {
    pub rel_path: String,
    pub doc_type: &'static str,
    pub tax_year: Option<u16>,
    pub client_id: &'static str,
    pub ssn: Option<String>,
    pub ein: Option<String>,
}

#[derive(Debug, Default)]
pub struct Summary {
    pub clients: usize,
    pub docs: Vec<FixtureDoc>,
}

const FIRST: &[&str] = &[
    "Avery", "Jordan", "Riley", "Casey", "Morgan", "Quinn", "Rowan", "Emerson",
];
const LAST: &[&str] = &[
    "Testwell",
    "Samplefield",
    "Fixtureson",
    "Mockley",
    "Demoreaux",
    "Placeholt",
];
const BIZ: &[&str] = &[
    "Synthetic Orchards",
    "Example Freight",
    "Sample Supply",
    "Mock Harbor",
];
const PAYERS: &[&str] = &[
    "Placeholder Bank NA",
    "Fictional Brokerage",
    "Sample Payroll Co",
    "Demo Credit Union",
];

/// Per-year documents: (doc type, Filer template folder, has SSN, has EIN).
const INDIVIDUAL_DOCS: &[(&str, &str, bool, bool)] = &[
    ("W-2", "Income Tax", true, true),
    ("1099-INT", "Income Tax", true, true),
    ("1099-DIV", "Income Tax", true, true),
    ("Organizer", "Income Tax", true, false),
    ("1040 Return", "Income Tax", true, false),
    ("Engagement Letter", "Correspondence", false, false),
];
const BUSINESS_DOCS: &[(&str, &str, bool, bool)] = &[
    ("Bank Statement", "Bookkeeping", false, false),
    ("941", "Payroll", false, true),
    ("Trial Balance", "Financials", false, false),
    ("K-1", "Income Tax", true, true),
    ("1065 Return", "Income Tax", false, true),
    ("Engagement Letter", "Correspondence", false, false),
];

/// Writes the cabinet into `out` (must not exist, or must be an earlier fixture: it carries
/// `MARKER` and is replaced).
pub fn generate(out: &Path, seed: u64) -> Result<Summary> {
    if out.exists() {
        if !out.join(MARKER).is_file() {
            bail!(
                "{} exists and is not a generated fixture; refusing to touch it",
                out.display()
            );
        }
        std::fs::remove_dir_all(out).with_context(|| format!("removing old {}", out.display()))?;
    }
    std::fs::create_dir_all(out)?;
    std::fs::write(
        out.join(MARKER),
        "generated by vf-fixtures; safe to delete\n",
    )?;

    let mut rng = Rng::new(seed);
    let firm = rng.uuid();
    cabinet::create(
        out,
        &CabinetFile {
            cabinet_id: rng.uuid().to_string(),
            firm_id: firm.to_string(),
            schema_version: vf_core::db::SCHEMA_VERSION,
            layout_version: 1,
            created: "2026-11-02T00:00:00Z".into(),
            name: None,
        },
    )
    .map_err(anyhow::Error::msg)?;

    let mut clients = Vec::new();
    for (i, id) in ["1001", "1002", "1003", "1004", "1005"]
        .into_iter()
        .enumerate()
    {
        let kind = if i < 3 {
            Kind::Individual
        } else {
            Kind::Business
        };
        let name = match kind {
            Kind::Individual => format!("{}, {}", rng.pick(LAST), rng.pick(FIRST)),
            Kind::Business => format!("{} LLC", BIZ[i - 3]),
        };
        clients.push(FixtureClient { id, name, kind });
    }

    let mut summary = Summary {
        clients: clients.len(),
        ..Summary::default()
    };
    for c in &clients {
        let folder = out.join(format!("{} ({})", c.name, c.id));
        std::fs::create_dir_all(&folder)?;
        let fc = Client {
            id: c.id.into(),
            uuid: rng.uuid(),
            name: c.name.clone(),
            extra: BTreeMap::new(),
        };
        filer_intake::sentinel::write_sentinel(out, &folder, &fc, firm)
            .map_err(anyhow::Error::msg)?;
        let ssn = synthetic_ssn(rng.next_u64());
        let client_ein = synthetic_ein(&mut rng);
        let set = match c.kind {
            Kind::Individual => INDIVIDUAL_DOCS,
            Kind::Business => BUSINESS_DOCS,
        };
        for year in YEARS {
            for &(doc_type, top, has_ssn, has_ein) in set {
                let ein = has_ein.then(|| match c.kind {
                    Kind::Business => client_ein.clone(),
                    Kind::Individual => synthetic_ein(&mut rng),
                });
                let ssn = has_ssn.then(|| ssn.clone());
                let file = format!("{}_{}_{}_{}.pdf", c.name, c.id, doc_type, year);
                let rel = format!("{} ({})/{top}/{year}/{file}", c.name, c.id);
                let mut lines = vec![
                    format!("{doc_type} - tax year {year}"),
                    "SYNTHETIC TEST DOCUMENT - NOT REAL DATA".into(),
                    format!("Client: {} ({})", c.name, c.id),
                    format!("Payer: {}", rng.pick(PAYERS)),
                ];
                if let Some(e) = &ein {
                    lines.push(format!("Payer EIN: {e}"));
                }
                if let Some(s) = &ssn {
                    lines.push(format!("Recipient SSN: {s}"));
                }
                lines.push(format!(
                    "Amount: {}.{:02}",
                    1000 + rng.next_u64() % 90_000,
                    rng.next_u64() % 100
                ));
                write_pdf(&out.join(&rel), &lines)?;
                summary.docs.push(FixtureDoc {
                    rel_path: rel,
                    doc_type,
                    tax_year: Some(year),
                    client_id: c.id,
                    ssn,
                    ein,
                });
            }
        }
    }
    Ok(summary)
}

/// One-page PDF (US Letter, Helvetica) with a text layer, one line per entry.
pub fn write_pdf(path: &Path, lines: &[String]) -> Result<()> {
    let (catalog, pages, page, font, content_id) = (
        Ref::new(1),
        Ref::new(2),
        Ref::new(3),
        Ref::new(4),
        Ref::new(5),
    );
    let mut pdf = Pdf::new();
    pdf.catalog(catalog).pages(pages);
    pdf.pages(pages).kids([page]).count(1);
    let mut p = pdf.page(page);
    p.media_box(Rect::new(0.0, 0.0, 612.0, 792.0));
    p.parent(pages);
    p.contents(content_id);
    p.resources().fonts().pair(Name(b"F1"), font);
    drop(p);
    pdf.type1_font(font).base_font(Name(b"Helvetica"));
    let mut c = Content::new();
    c.begin_text();
    c.set_font(Name(b"F1"), 12.0);
    c.next_line(72.0, 720.0);
    for (i, l) in lines.iter().enumerate() {
        if i > 0 {
            c.next_line(0.0, -18.0);
        }
        c.show(Str(l.as_bytes()));
    }
    c.end_text();
    pdf.stream(content_id, &c.finish());
    let parent: PathBuf = path.parent().context("pdf path has a folder")?.into();
    std::fs::create_dir_all(&parent)?;
    std::fs::write(path, pdf.finish())?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use vf_core::db::{CatalogKey, Storage};

    fn tree(dir: &Path) -> Vec<(String, Vec<u8>)> {
        fn walk(base: &Path, d: &Path, out: &mut Vec<(String, Vec<u8>)>) {
            let mut es: Vec<_> = std::fs::read_dir(d)
                .unwrap()
                .map(|e| e.unwrap().path())
                .collect();
            es.sort();
            for p in es {
                let rel = p.strip_prefix(base).unwrap().to_string_lossy().into_owned();
                if p.is_dir() {
                    walk(base, &p, out);
                } else if p.extension().is_some_and(|e| e == "pdf") {
                    out.push((rel, std::fs::read(&p).unwrap()));
                }
            }
        }
        let mut out = Vec::new();
        walk(dir, dir, &mut out);
        out
    }

    #[test]
    fn five_clients_sixty_pdfs_deterministic() {
        let tmp = tempfile::tempdir().unwrap();
        let (a, b) = (tmp.path().join("a"), tmp.path().join("b"));
        let s = generate(&a, 42).unwrap();
        generate(&b, 42).unwrap();
        assert_eq!(s.clients, 5);
        assert_eq!(s.docs.len(), 60);
        assert_eq!(tree(&a), tree(&b), "same seed, same files and bytes");
        // Regenerating over a fixture replaces it; over anything else is refused.
        generate(&a, 42).unwrap();
        let other = tmp.path().join("other");
        std::fs::create_dir(&other).unwrap();
        assert!(generate(&other, 42).is_err());
    }

    #[test]
    fn identifiers_are_never_issued_values() {
        let tmp = tempfile::tempdir().unwrap();
        let s = generate(&tmp.path().join("c"), 7).unwrap();
        let ssns: Vec<_> = s.docs.iter().filter_map(|d| d.ssn.as_deref()).collect();
        let eins: Vec<_> = s.docs.iter().filter_map(|d| d.ein.as_deref()).collect();
        assert!(!ssns.is_empty() && !eins.is_empty());
        assert!(
            ssns.iter()
                .all(|x| x.starts_with("987-65-432") && x.len() == 11)
        );
        for e in eins {
            let p: u8 = e[..2].parse().unwrap();
            assert!(NEVER_ISSUED_EIN_PREFIXES.contains(&p), "{e}");
            assert_eq!(e.len(), 10);
        }
    }

    #[test]
    fn pdfs_have_a_readable_text_layer() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().join("c");
        let s = generate(&root, 42).unwrap();
        let doc = s.docs.iter().find(|d| d.ssn.is_some()).unwrap();
        let path = root.join(&doc.rel_path);
        assert_eq!(lopdf::Document::load(&path).unwrap().get_pages().len(), 1);
        let dir = filer_pdf::pdf::find_pdfium(Path::new("")).expect("pdfium");
        let pdfium = filer_pdf::pdf::pdfium(&dir).unwrap();
        let text = filer_pdf::pdf::page_texts(pdfium, &path)
            .unwrap()
            .join("\n");
        assert!(text.contains(doc.ssn.as_deref().unwrap()), "{text}");
        assert!(text.contains("SYNTHETIC TEST DOCUMENT"));
    }

    /// P00 done-when: rebuild on the fixture cabinet produces the expected row counts.
    #[test]
    fn rebuild_of_fixture_gives_expected_rows() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().join("cabinet");
        let s = generate(&root, 42).unwrap();
        let mut conn = vf_core::db::open(
            &tmp.path().join("catalog.db"),
            &CatalogKey([8; 32]),
            Storage::Local,
        )
        .unwrap();
        let rep = vf_fs::rebuild::rebuild(&mut conn, &root, "dev-fixture").unwrap();
        assert_eq!(rep.clients, 5);
        assert_eq!(rep.docs_new, 60);
        assert!(rep.unbound_folders.is_empty() && rep.duplicate_folders.is_empty());
        let n = |sql: &str| -> i64 { conn.query_row(sql, [], |r| r.get(0)).unwrap() };
        assert_eq!(n("SELECT count(*) FROM client"), 5);
        assert_eq!(n("SELECT count(*) FROM document"), 60);
        assert_eq!(
            n("SELECT count(*) FROM document WHERE client_id IS NULL"),
            0
        );
        for y in YEARS {
            let want = s.docs.iter().filter(|d| d.tax_year == Some(y)).count() as i64;
            assert_eq!(
                n(&format!(
                    "SELECT count(*) FROM document WHERE tax_year = {y}"
                )),
                want
            );
        }
        assert_eq!(n("SELECT count(DISTINCT hash) FROM document"), 60);
        assert_eq!(n("SELECT count(*) FROM version"), 0);
        let again = vf_fs::rebuild::rebuild(&mut conn, &root, "dev-fixture").unwrap();
        assert_eq!(again.docs_unchanged, 60);
    }
}
